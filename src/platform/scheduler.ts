export interface TaskInfo {
  installed: boolean;
  enabled: boolean;
  command: string;
  arguments: string;
  lastResult: string;
  lastRunTime: string;
  status: string;
}

export interface TaskManager {
  installed(name: string): boolean;
  query(name: string): TaskInfo;
  create(name: string, spec: TaskSpec): void;
  delete(name: string): void;
  start(name: string): void;
  stop(name: string): void;
}

export function currentUser(): string {
  const domain = process.env.USERDOMAIN;
  const name = process.env.USERNAME;
  if (domain && name) return `${domain}\\${name}`;
  const result = run(["whoami.exe"]);
  if (result.code === 0 && result.out.trim()) return result.out.trim();
  throw new Error("cannot tell which Windows user this is");
}

function tag(xml: string, name: string): string {
  return new RegExp(`<${name}>([^<]*)</${name}>`).exec(xml)?.[1]?.trim() ?? "";
}

export const windowsTaskManager: TaskManager = {
  installed(name: string): boolean {
    return run(["schtasks.exe", "/Query", "/TN", name]).code === 0;
  },

  query(name: string): TaskInfo {
    const result = run(["schtasks.exe", "/Query", "/TN", name, "/XML"]);
    if (result.code !== 0) {
      return {
        installed: false,
        enabled: false,
        command: "",
        arguments: "",
        lastResult: "",
        lastRunTime: "",
        status: "",
      };
    }
    const settings = /<Settings>[\s\S]*?<\/Settings>/.exec(result.out)?.[0] ?? "";
    return {
      installed: true,
      enabled: !/<Enabled>\s*false\s*<\/Enabled>/i.test(settings),
      command: tag(result.out, "Command"),
      arguments: tag(result.out, "Arguments"),
      lastResult: tag(result.out, "LastResult"),
      lastRunTime: tag(result.out, "LastRunTime"),
      status: tag(result.out, "Status"),
    };
  },

  create(name: string, spec: TaskSpec): void {
    const dir = mkdtempSync(join(tmpdir(), "msoutlook-mcp-task-"));
    const file = join(dir, "task.xml");
    writeFileSync(file, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(taskXml(spec), "utf16le")]));
    try {
      const result = run(["schtasks.exe", "/Create", "/TN", name, "/XML", file, "/F"]);
      if (result.code !== 0) {
        throw new Error(`schtasks could not register "${name}": ${(result.err || result.out).trim()}`);
      }
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  },

  delete(name: string): void {
    const result = run(["schtasks.exe", "/Delete", "/TN", name, "/F"]);
    if (result.code !== 0) {
      throw new Error(`schtasks could not remove "${name}": ${(result.err || result.out).trim()}`);
    }
  },

  start(name: string): void {
    const result = run(["schtasks.exe", "/Run", "/TN", name]);
    if (result.code !== 0) {
      throw new Error(`schtasks could not start "${name}": ${(result.err || result.out).trim()}`);
    }
  },

  stop(name: string): void {
    run(["schtasks.exe", "/End", "/TN", name]);
  },
};

/**
 * Classic Outlook's executable from the App Paths registry key. No hardcoded
 * Office path; a machine may have a different edition or channel.
 */
export function findOutlookExe(): string | null {
  const keys = [
    "HKLM\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\App Paths\\outlook.exe",
    "HKLM\\SOFTWARE\\WOW6432Node\\Microsoft\\Windows\\CurrentVersion\\App Paths\\outlook.exe",
    "HKCU\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\App Paths\\outlook.exe",
  ];
  for (const key of keys) {
    const result = run(["reg.exe", "query", key, "/ve"]);
    if (result.code !== 0) continue;
    const match = /REG_SZ\s+(.+)$/m.exec(result.out);
    if (match?.[1]) {
      const value = match[1].trim().replace(/^"|"$/g, "");
      if (value) return value;
    }
  }
  return null;
}

/**
 * Best effort: the new Outlook preference lives in the Office version key.
 * Returns null when it cannot be read, so callers say "unknown" instead of
 * pretending. This key is unverified against a real installation.
 */
export function newOutlookDefault(): boolean | null {
  const result = run(["reg.exe", "query", "HKCU\\Software\\Microsoft\\Office\\16.0\\Outlook\\Preferences", "/v", "UseNewOutlook"]);
  if (result.code !== 0) return null;
  const match = /REG_DWORD\s+0x([0-9a-f]+)/i.exec(result.out);
  if (!match?.[1]) return null;
  return Number.parseInt(match[1], 16) === 1;
}

/** Constrained-language mode blocks New-Object -ComObject. */
export function powershellLanguageMode(): string {
  const root = process.env.SystemRoot ?? "C:\\Windows";
  const exe = join(root, "System32", "WindowsPowerShell", "v1.0", "powershell.exe");
  const result = run([
    exe,
    "-NoLogo",
    "-NoProfile",
    "-NonInteractive",
    "-Command",
    "$ExecutionContext.SessionState.LanguageMode",
  ]);
  return result.code === 0 ? result.out.trim() : "";
}
